// Copia a casca montada (casca/saida) para dentro do projeto Android e regenera os arquivos do Capacitor (`cap sync android`).
// Depois do sync, devolve o caminho do Capacitor em android/capacitor.settings.gradle para `../node_modules/...`: o CLI escreve o
// caminho REAL da pasta (numa pasta de node_modules ligada por junção ou link, sai o caminho da outra cópia do repositório), e isso
// não pode ir para o git nem mudar de uma máquina para outra (build reproduzível).
// Uso (na raiz, depois de `node casca/montar.mjs`): node casca/android.mjs
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const raiz = path.resolve(import.meta.dirname, "..");
if (!fs.existsSync(path.join(raiz, "casca/saida/index.html"))) {
  console.error("casca/saida não montada: rode antes `node casca/montar.mjs`");
  process.exit(1);
}
const cli = path.join(raiz, "node_modules/@capacitor/cli/bin/capacitor");
const r = spawnSync(process.execPath, [cli, "sync", "android"], { cwd: raiz, stdio: "inherit", env: { ...process.env, CAPACITOR_TELEMETRY: "false" } });
if (r.status !== 0) process.exit(r.status ?? 1);

export const CONFIGURACAO_DO_CAPACITOR = [
  `// DO NOT EDIT THIS FILE! IT IS GENERATED EACH TIME "capacitor update" IS RUN`,
  `include ':capacitor-android'`,
  `project(':capacitor-android').projectDir = new File('../node_modules/@capacitor/android/capacitor')`,
  "",
].join("\n");
fs.writeFileSync(path.join(raiz, "android/capacitor.settings.gradle"), CONFIGURACAO_DO_CAPACITOR);
console.log("android sincronizado (casca/saida → android/app/src/main/assets/public)");
