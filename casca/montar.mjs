// Monta a casca do chat (onda R3, item 1.2) em casca/saida, o `webDir` do app:
//   1. copia os WebAssembly do chat para casca/public/cifra (o motor @wireapp/core-crypto, da versão instalada; o do SPQR quando
//      existir em public/cifra): o app não baixa nada disso de servidor nenhum;
//   2. roda o `next build` da casca (estático, `output: "export"`), com a hora fixa (SOURCE_DATE_EPOCH) e sem telemetria;
//   3. põe a política de segurança (CSP) no <head> de cada HTML, com o resumo SHA-256 de cada script em linha do próprio build;
//   4. escreve o resumo da árvore (sha256 de cada arquivo, em ordem) em casca/arvore.sha256: duas montagens do mesmo commit dão o
//      mesmo resumo (scripts/testar-r3-android-build.mjs confere).
// Uso (na raiz): node casca/montar.mjs    Variáveis: NEXT_PUBLIC_SUPABASE_URL, NEXT_PUBLIC_SUPABASE_ANON_KEY, NEXT_PUBLIC_ALUMIA_APP_BASE.
import { spawnSync } from "node:child_process";
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const raiz = path.resolve(import.meta.dirname, "..");
const casca = path.join(raiz, "casca");
const saida = path.join(casca, "saida");

// 1. Os WebAssembly do chat.
const destino = path.join(casca, "public/cifra");
fs.rmSync(destino, { recursive: true, force: true });
fs.mkdirSync(destino, { recursive: true });
const motor = path.join(raiz, "node_modules/@wireapp/core-crypto");
const versao = JSON.parse(fs.readFileSync(path.join(motor, "package.json"), "utf8")).version;
fs.copyFileSync(path.join(motor, "dist/autogenerated/wasm-bindgen/index_bg.wasm"), path.join(destino, `core-crypto-${versao}.wasm`));
const publico = path.join(raiz, "public/cifra");
if (fs.existsSync(publico)) for (const f of fs.readdirSync(publico)) if (/^spqr-[\d.]+\.wasm$/.test(f)) fs.copyFileSync(path.join(publico, f), path.join(destino, f));

// 2. O build estático.
fs.rmSync(saida, { recursive: true, force: true });
const env = { ...process.env, NEXT_TELEMETRY_DISABLED: "1", SOURCE_DATE_EPOCH: process.env.SOURCE_DATE_EPOCH ?? "1763424000", NODE_ENV: "production" };
const r = spawnSync(process.execPath, [path.join(raiz, "node_modules/next/dist/bin/next"), "build", "--webpack", casca], { cwd: raiz, env, stdio: "inherit" });
if (r.status !== 0) process.exit(r.status ?? 1);
// O que o Next deixa na saída e não é da página (cache e rastros do build) não vai para o app.
for (const lixo of ["cache", "trace", "trace-build", "types", "diagnostics"]) fs.rmSync(path.join(saida, lixo), { recursive: true, force: true });

// 3. A política de segurança em cada HTML.
const supabase = (() => {
  try {
    return new URL(process.env.NEXT_PUBLIC_SUPABASE_URL ?? "").origin;
  } catch {
    return "";
  }
})();
const arquivos = (pasta) =>
  fs.readdirSync(pasta, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? arquivos(path.join(pasta, e.name)) : [path.join(pasta, e.name)]));
for (const html of arquivos(saida).filter((f) => f.endsWith(".html"))) {
  let texto = fs.readFileSync(html, "utf8");
  const resumos = new Set();
  for (const m of texto.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g)) if (m[1]) resumos.add(`'sha256-${crypto.createHash("sha256").update(m[1]).digest("base64")}'`);
  const csp = [
    "default-src 'self'",
    `script-src 'self' 'wasm-unsafe-eval' ${[...resumos].sort().join(" ")}`.trim(),
    // O serviço de contas (entrar, sessão) pelo WebView; as rotas do Instituto saem pelo HTTP nativo e não precisam estar aqui. A ponte
    // do Tauri (os comandos do app do computador) fala por ipc: e http://ipc.localhost; no Android, as duas não têm efeito.
    `connect-src 'self' ipc: http://ipc.localhost${supabase ? ` ${supabase}` : ""}`,
    "img-src 'self' data: blob:",
    "style-src 'self' 'unsafe-inline'",
    "font-src 'self'",
    "worker-src 'self' blob:",
    "media-src 'self' blob:",
    "frame-src 'none'",
    "object-src 'none'",
    "base-uri 'none'",
    "form-action 'none'",
  ].join("; ");
  texto = texto.replace(/<head>/, `<head><meta http-equiv="Content-Security-Policy" content="${csp}">`);
  fs.writeFileSync(html, texto);
}

// 4. O resumo da árvore.
const linhas = arquivos(saida)
  .map((f) => path.relative(saida, f).split(path.sep).join("/"))
  .sort()
  .map((rel) => `${crypto.createHash("sha256").update(fs.readFileSync(path.join(saida, rel))).digest("hex")}  ${rel}`);
fs.writeFileSync(path.join(casca, "arvore.sha256"), `${linhas.join("\n")}\n`);
const total = crypto.createHash("sha256").update(linhas.join("\n")).digest("hex");
console.log(`casca montada: ${linhas.length} arquivos, árvore ${total}`);
