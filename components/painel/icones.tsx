/** Os ícones dos 8 espaços, pelo nome que estrutura.ts guarda. */
const DOS_ESPACOS: Record<NomeDoIconeDoEspaco, LucideIcon> = { House, PenTool, CheckCheck, HeartHandshake, Users, Settings2, Shield, UserRound };
export const iconeDoEspaco = (nome: NomeDoIconeDoEspaco): LucideIcon => DOS_ESPACOS[nome] ?? House;

/** O componente Lucide de uma seção (para quem quer passar como "simbolo"). */
export const iconeDe = (id: string): LucideIcon => icones[id] ?? LayoutDashboard;

/** O ícone de uma seção, com a mesma API de antes (quem já chama <Icone id className /> não muda). */
export function Icone({ id, className = "h-[18px] w-[18px]" }: { id: string; className?: string }) {
  // O componente vem pronto do mapa acima (não é criado aqui): createElement deixa isso claro para o compilador do React.
  return createElement(iconeDe(id), { "aria-hidden": true, className: `shrink-0 ${className}`, strokeWidth: 1.8 });
}
