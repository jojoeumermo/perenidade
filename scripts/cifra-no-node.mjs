// Carrega o motor de cifra do chat (@wireapp/core-crypto, lib/rede/cifra/motor.ts) dentro do Node, para os testes. A biblioteca é
// feita para o navegador: ela recusa iniciar sem `window` e busca o WebAssembly por endereço. Aqui o teste põe `globalThis.window`
// e entrega o arquivo do próprio node_modules como endereço `data:` (o fetch do Node lê). Só para teste: o site nunca usa isto.
import fs from "node:fs";
import { fileURLToPath } from "node:url";
import { carregarMotor } from "../lib/rede/cifra/motor.ts";

export async function motorNoNode() {
  globalThis.window ??= globalThis;
  // O pacote só exporta o módulo; o WebAssembly fica ao lado dele, em dist/autogenerated/wasm-bindgen/.
  const modulo = fileURLToPath(import.meta.resolve("@wireapp/core-crypto"));
  const wasm = fs.readFileSync(modulo.replace(/corecrypto\.js$/, "autogenerated/wasm-bindgen/index_bg.wasm"));
  return carregarMotor(`data:application/wasm;base64,${wasm.toString("base64")}`);
}
