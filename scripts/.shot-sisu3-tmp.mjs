import { chromium } from 'playwright-core';
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox','--disable-gpu','--disable-dev-shm-usage','--headless=new','--no-proxy-server'] });
const page = await browser.newPage({ viewport: { width: 1100, height: 1300 } });
setTimeout(() => { console.log('WATCHDOG'); process.exit(2); }, 55000);
page.setDefaultTimeout(60000);
await page.goto('http://127.0.0.1:3100/pt/enem/sisu', { waitUntil: 'domcontentloaded', timeout: 60000 });
await page.waitForTimeout(2200);
await page.evaluate(() => { for (const d of document.querySelectorAll('dialog[open]')) d.close(); });
await page.locator('input[placeholder*="Medicina"]').fill('canguaretama');
await page.waitForTimeout(1200);
await page.evaluate(() => window.scrollTo(0, 500));
await page.screenshot({ path: '/downloads/sisu-v3-detalhes.png' });
const t = await page.evaluate(() => document.body.innerText);
console.log('habCHS:', t.includes('habilitação Ciências Humanas e Sociais'), '| habMT:', t.includes('habilitação Matemática'), '| 537,64:', t.includes('537,64'), '| 489,86:', t.includes('489,86'));
await browser.close(); process.exit(0);
