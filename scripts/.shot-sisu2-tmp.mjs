import { chromium } from 'playwright-core';
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox','--disable-gpu','--disable-dev-shm-usage','--headless=new','--no-proxy-server'] });
const page = await browser.newPage({ viewport: { width: 1100, height: 1200 } });
setTimeout(() => { console.log('WATCHDOG'); process.exit(2); }, 60000);
page.setDefaultTimeout(60000);
await page.goto('http://127.0.0.1:3100/pt/enem/sisu', { waitUntil: 'domcontentloaded', timeout: 60000 });
await page.waitForTimeout(2200);
await page.evaluate(() => { for (const d of document.querySelectorAll('dialog[open]')) d.close(); });
await page.locator('input[placeholder*="Medicina"]').fill('escola de teatro');
await page.waitForTimeout(1200);
await page.evaluate(() => window.scrollTo(0, 600));
await page.screenshot({ path: '/downloads/sisu-v2-completo.png' });
const t = await page.evaluate(() => document.body.innerText);
console.log('conferidos:', t.includes('conferidas oferta por oferta com os relatórios oficiais'), '| 2021:', t.includes('não validada'), '| pesos:', t.includes('não foram conferidos com os termos de adesão'), '| zero neutro:', t.includes('registra 0 nesses casos'), '| UFBA2023:', t.includes('678,00') && t.includes('680,88'));
await browser.close();
process.exit(0);
