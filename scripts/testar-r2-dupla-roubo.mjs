// Aceite do item 1.1 da onda R2: "roubar o estado da sessão num momento não permite ler depois da próxima troca de DH". Roda no
// navegador (Edge sem janela, pelo Playwright), porque só lá o motor (@wireapp/core-crypto) grava a loja num arquivo (OPFS) que dá
// para COPIAR, como faria quem rouba o aparelho:
//   carga 1: Ana e Bia, cada uma com a loja no OPFS, abrem a sessão Proteus e trocam uma ida e volta; a Ana manda "a1".
//   carga 2: a loja da Bia é COPIADA ("roubo", o estado naquele momento); a Bia lê "a1" e responde "b1" (troca de DH); a Ana lê
//            "b1" e manda "a2".
//   carga 3: quem tem a cópia abre a loja roubada: lê "a1" (prova de que o estado roubado é de verdade) e NÃO lê "a2".
// O servidor de teste só serve o motor e uma página em branco, em 127.0.0.1 com porta sorteada, e é desligado no fim.
// Uso: node scripts/testar-r2-dupla-roubo.mjs
import fs from "node:fs";
import http from "node:http";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright";

const raiz = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const pasta = path.join(raiz, "node_modules/@wireapp/core-crypto/dist");
const arquivos = {
  "/cc/corecrypto.js": [path.join(pasta, "corecrypto.js"), "text/javascript"],
  "/cc/index_bg.wasm": [path.join(pasta, "autogenerated/wasm-bindgen/index_bg.wasm"), "application/wasm"],
};
const servidor = http.createServer((pedido, resposta) => {
  const achado = arquivos[pedido.url];
  if (achado) {
    resposta.writeHead(200, { "content-type": achado[1] });
    fs.createReadStream(achado[0]).pipe(resposta);
  } else {
    resposta.writeHead(200, { "content-type": "text/html; charset=utf-8" });
    resposta.end("<!doctype html><title>teste</title>");
  }
});
await new Promise((ok) => servidor.listen(0, "127.0.0.1", ok));
const origem = `http://127.0.0.1:${servidor.address().port}`;

let certos = 0;
const falhas = [];
const confere = (nome, ok, detalhe = "") => (ok ? certos++ : falhas.push(`${nome}${detalhe ? `: ${detalhe}` : ""}`));

const navegador = await chromium.launch({ channel: "msedge" });
const contexto = await navegador.newContext();
// Funções que rodam DENTRO da página (o motor, a loja no OPFS, a cópia da loja).
const PREPARO = `
  window.motor = async () => { const M = await import("/cc/corecrypto.js"); await M.initWasmModule("/cc/index_bg.wasm"); return M; };
  window.loja = async (M, nome, chave = nome === "ana" ? 1 : 2) => { const cc = M.CoreCrypto.new(await M.Database.open(nome, new M.DatabaseKey(new Uint8Array(32).fill(chave)))); await cc.transaction((c) => c.proteusInit()); return cc; };
  window.b64 = (b) => btoa(String.fromCharCode(...b));
  window.deB64 = (s) => Uint8Array.from(atob(s), (c) => c.charCodeAt(0));
  window.copiarLoja = async (de, para) => {
    const raiz = await (await navigator.storage.getDirectory()).getDirectoryHandle("core-crypto");
    const nomes = [];
    async function copiar(origem, destino) {
      for await (const [nome, h] of origem.entries()) {
        if (h.kind === "file") {
          const w = await (await destino.getFileHandle(nome, { create: true })).createWritable();
          await w.write(await (await h.getFile()).arrayBuffer());
          await w.close();
          nomes.push(nome);
        } else await copiar(h, await destino.getDirectoryHandle(nome, { create: true }));
      }
    }
    let achou = false;
    for await (const [nome, h] of raiz.entries()) {
      if (nome === de) { achou = true; if (h.kind === "file") { const w = await (await raiz.getFileHandle(para, { create: true })).createWritable(); await w.write(await (await h.getFile()).arrayBuffer()); await w.close(); nomes.push(nome); } else await copiar(h, await raiz.getDirectoryHandle(para, { create: true })); }
      else if (nome.startsWith(de + "-")) { const w = await (await raiz.getFileHandle(para + nome.slice(de.length), { create: true })).createWritable(); await w.write(await (await h.getFile()).arrayBuffer()); await w.close(); nomes.push(nome); }
    }
    return { achou, nomes };
  };
`;
async function carga(fn, arg) {
  const pagina = await contexto.newPage();
  await pagina.goto(`${origem}/`);
  await pagina.addScriptTag({ content: PREPARO });
  try {
    return await pagina.evaluate(fn, arg);
  } finally {
    await pagina.close();
  }
}

try {
  // Carga 1.
  const um = await carga(async () => {
    const M = await window.motor();
    const T = (s) => new TextEncoder().encode(s);
    const [ana, bia] = [await window.loja(M, "ana"), await window.loja(M, "bia")];
    const pre = await bia.transaction((c) => c.proteusNewPrekeyAuto());
    await ana.transaction((c) => c.proteusSessionFromPrekey("bia", pre.pkb));
    const m1 = await ana.transaction((c) => c.proteusEncrypt("bia", T("m1")));
    await bia.transaction((c) => c.proteusDecryptSafe("ana", m1));
    const r1 = await bia.transaction((c) => c.proteusEncrypt("ana", T("r1")));
    await ana.transaction((c) => c.proteusDecryptSafe("bia", r1));
    const a1 = await ana.transaction((c) => c.proteusEncrypt("bia", T("a1")));
    return { a1: window.b64(a1) };
  });
  // Carga 2: copia a loja da Bia ANTES de ela ler a1 (o estado roubado), depois a conversa segue com troca de DH.
  const dois = await carga(async (um) => {
    const copia = await window.copiarLoja("bia", "roubo");
    const M = await window.motor();
    const T = (s) => new TextEncoder().encode(s);
    const D = (b) => new TextDecoder().decode(b);
    const [ana, bia] = [await window.loja(M, "ana"), await window.loja(M, "bia")];
    const a1 = D(await bia.transaction((c) => c.proteusDecryptSafe("ana", window.deB64(um.a1))));
    const b1 = await bia.transaction((c) => c.proteusEncrypt("ana", T("b1")));
    const lidaB1 = D(await ana.transaction((c) => c.proteusDecryptSafe("bia", b1)));
    const a2 = await ana.transaction((c) => c.proteusEncrypt("bia", T("a2")));
    const a2Bia = D(await bia.transaction((c) => c.proteusDecryptSafe("ana", a2)));
    return { copia, a1, lidaB1, a2Bia, b1: window.b64(b1), a2: window.b64(a2) };
  }, um);
  confere("roubo: a loja da Bia foi copiada do OPFS", dois.copia.achou && dois.copia.nomes.length > 0, JSON.stringify(dois.copia));
  confere("roubo: a conversa de verdade segue (a1, b1, a2 lidas)", dois.a1 === "a1" && dois.lidaB1 === "b1" && dois.a2Bia === "a2", JSON.stringify(dois));
  // Carga 3: quem roubou.
  const tres = await carga(async ({ um, dois }) => {
    const M = await window.motor();
    const D = (b) => new TextDecoder().decode(b);
    const ladrao = await window.loja(M, "roubo", 2);
    const tentar = async (b64) => {
      try {
        return D(await ladrao.transaction((c) => c.proteusDecryptSafe("ana", window.deB64(b64))));
      } catch (e) {
        return `recusada: ${String(e?.message ?? e).slice(0, 80)}`;
      }
    };
    // a2 ANTES de a1: assim a leitura de a1 não muda o que o ladrão tem para tentar as outras.
    const a2 = await tentar(dois.a2);
    const a1 = await tentar(um.a1);
    return { a1, a2 };
  }, { um, dois });
  console.log(`  (com a cópia: a1 → ${tres.a1}; a2 → ${tres.a2})`);
  confere("roubo: o estado copiado é de verdade (lê a1, mandada antes da troca de DH)", tres.a1 === "a1", tres.a1);
  confere("ACEITE 1.1: com o estado roubado, a mensagem depois da troca de DH (a2) NÃO abre", tres.a2 !== "a2" && tres.a2.startsWith("recusada"), tres.a2);
} catch (erro) {
  falhas.push(`erro: ${erro?.message ?? erro}`.slice(0, 300));
} finally {
  await navegador.close();
  servidor.close();
}
console.log(`${certos} certos, ${falhas.length} falhas`);
for (const f of falhas) console.log(`  ✗ ${f}`);
process.exit(falhas.length ? 1 : 0);
