import { chromium } from 'playwright-core';
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox','--disable-gpu','--disable-dev-shm-usage','--headless=new','--no-proxy-server'] });
const page = await browser.newPage({ viewport: { width: 1100, height: 1400 } });
setTimeout(() => { console.log('WATCHDOG'); process.exit(2); }, 90000);
page.setDefaultTimeout(60000);
await page.goto('http://127.0.0.1:3100/pt/enem/sisu', { waitUntil: 'domcontentloaded', timeout: 60000 });
await page.waitForTimeout(2500);
await page.evaluate(() => { for (const d of document.querySelectorAll('dialog[open]')) d.close(); });
await page.locator('input[placeholder*="Medicina"]').fill('museologia');
await page.waitForTimeout(1500);
await page.locator('text=SEM NOTA DE CORTE NOS DADOS').scrollIntoViewIfNeeded();
await page.waitForTimeout(400);
await page.screenshot({ path: '/downloads/sisu-semcorte-museologia2.png' });
const t = await page.evaluate(() => document.body.innerText);
console.log('secao:', /SEM NOTA DE CORTE NOS DADOS HISTÓRICOS CONSULTADOS \(2020–2025\)/.test(t));
console.log('vagas23:', t.includes('Consta no Sisu 2025 com 23 vagas na ampla concorrência.'));
console.log('lara:', t.includes('Laranjeiras/SE'));
await browser.close(); process.exit(0);
