import { chromium } from 'playwright-core';
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox','--disable-gpu','--disable-dev-shm-usage','--headless=new','--no-proxy-server'] });
const page = await browser.newPage({ viewport: { width: 1100, height: 1400 } });
page.on('pageerror', (e) => console.log('PAGEERROR:', String(e).slice(0,200)));
page.on('requestfailed', (r) => console.log('REQFAIL:', r.url().slice(0,120), r.failure()?.errorText));
page.on('response', (r) => { if (r.url().includes('laboratorio-tri') || r.url().includes('enem-2025')) console.log('RESP:', r.status(), r.url().slice(0,120)); });
setTimeout(() => { console.log('WATCHDOG'); process.exit(2); }, 60000);
page.setDefaultTimeout(90000);
await page.goto('http://127.0.0.1:3100/pt/enem/laboratorio-tri', { waitUntil: 'domcontentloaded', timeout: 90000 });
await page.waitForSelector('select', { timeout: 90000 });
await page.evaluate(() => { const d = document.querySelector('dialog[open]'); if (d) { const b = d.querySelector('button,[formmethod=dialog],form button'); if (b) b.click(); else d.close(); } });
await page.keyboard.press('Escape');
await page.waitForTimeout(400);
await page.evaluate(() => { for (const d of document.querySelectorAll('dialog[open]')) d.close(); });
await page.evaluate(() => { const setter = Object.getOwnPropertyDescriptor(HTMLSelectElement.prototype,'value').set; for (const s of document.querySelectorAll('select')) { if ([...s.options].some((o)=>o.value==='2025')) { setter.call(s,'2025'); s.dispatchEvent(new Event('change',{bubbles:true})); break; } } });
await page.waitForSelector('table tbody tr', { timeout: 90000 });
await page.$$eval('input[type=checkbox]:not([disabled])', (els) => els.forEach((e)=>e.click()));
await page.waitForTimeout(1500);
await page.evaluate(() => { for (const el of document.querySelectorAll('h2')) { if (el.innerText && el.innerText.startsWith('Questões anuladas')) { el.scrollIntoView({block:'start'}); break; } } });
await page.screenshot({ path: '/downloads/tri-pagina-integrada-cenarios.png' });
console.log('shot1 ok');
for (const b of await page.$$('button')) { const t = await b.innerText(); if (t.includes('Sim, marquei')) { await b.click(); break; } }
await page.waitForTimeout(1000);
await page.evaluate(() => { for (const el of document.querySelectorAll('h2')) { if (el.innerText && el.innerText.startsWith('Questões anuladas')) { el.scrollIntoView({block:'start'}); break; } } });
await page.screenshot({ path: '/downloads/tri-pagina-integrada-fixa.png' });
console.log('shot2 ok');
const txt = await page.evaluate(() => document.body.innerText);
console.log('980:', txt.includes('980'), '| 968:', txt.includes('968'), '| ressalva:', txt.includes('não uma regra oficial do Inep nem garantia'));
await browser.close();
